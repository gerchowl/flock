/**
 * Compiles the design tokens (`tokens/*.json`, DTCG 2025.10) with Style
 * Dictionary into `src/tokens.css` and `src/tokens.ts` (#2895).
 *
 * Both outputs are committed. `bun run tokens` rewrites them; `bun run
 * tokens:check` (part of `just client-lint`) fails when either differs from
 * what the token files produce, so a stale output cannot land. Committing
 * keeps the Vite build and the nix bundle free of a generation step, and
 * lets `tsc` see the token union without running anything first.
 *
 * Each mode is its own token file, emitted as one `:root` block:
 *
 * - `base.json` and `color/light.json`: the defaults;
 * - `color/dark.json` under `prefers-color-scheme: dark` (it must define
 *   every light colour);
 * - `color/*-contrast.json` under `prefers-contrast: more` (overrides only);
 * - `phone.json` below the phone breakpoint (overrides only).
 *
 * @module
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import StyleDictionary from "style-dictionary";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const CSS_OUT = "src/tokens.css";
const TS_OUT = "src/tokens.ts";

/** The breakpoint `src/layout/phone.ts` and the phone shell use. */
export const PHONE_MEDIA = "(max-width: 767.98px)";

type Mode = { readonly files: readonly string[]; readonly media?: string; readonly complete?: boolean };

const DEFAULTS: Mode = { files: ["tokens/base.json", "tokens/color/light.json"] };
const MODES: readonly Mode[] = [
  DEFAULTS,
  { files: ["tokens/color/dark.json"], media: "(prefers-color-scheme: dark)", complete: true },
  { files: ["tokens/color/light-contrast.json"], media: "(prefers-contrast: more) and (prefers-color-scheme: light)" },
  { files: ["tokens/color/dark-contrast.json"], media: "(prefers-contrast: more) and (prefers-color-scheme: dark)" },
  { files: ["tokens/phone.json"], media: PHONE_MEDIA },
];

const HEADER = "Generated by scripts/tokens.ts from tokens/*.json. Do not edit; run `bun run tokens`.";

/** One mode's declarations, by CSS variable name, in source order. */
async function compile(mode: Mode): Promise<Map<string, string>> {
  const sd = new StyleDictionary({
    source: mode.files.map((file) => `${ROOT}/${file}`),
    usesDtcg: true,
    log: { verbosity: "silent", warnings: "error" },
    platforms: { css: { transformGroup: "css" } },
  });
  const { allTokens } = await sd.getPlatformTokens("css");
  return new Map(allTokens.map((token) => [token.name, String(token.$value)]));
}

function block(declarations: Map<string, string>, indent: string): string {
  const lines = [...declarations].map(([name, value]) => `${indent}  --${name}: ${value};`);
  return `${indent}:root {\n${lines.join("\n")}\n${indent}}`;
}

/** Both generated files, as text. */
export async function generate(): Promise<{ css: string; ts: string }> {
  const compiled = await Promise.all(MODES.map(compile));
  const defaults = compiled[0]!;
  const blocks = MODES.map((mode, index) => {
    const declarations = compiled[index]!;
    for (const name of declarations.keys()) {
      if (!defaults.has(name)) {
        throw new Error(`tokens: --${name} (${mode.files.join(", ")}) has no default in ${DEFAULTS.files.join(", ")}`);
      }
    }
    if (mode.complete) {
      const missing = [...defaults.keys()].filter((name) => name.startsWith("color-") && !declarations.has(name));
      if (missing.length > 0) {
        throw new Error(`tokens: ${mode.files.join(", ")} lacks ${missing.map((name) => `--${name}`).join(", ")}`);
      }
    }
    return mode.media === undefined
      ? block(declarations, "")
      : `@media ${mode.media} {\n${block(declarations, "  ")}\n}`;
  });
  const css = `/* ${HEADER} */\n\n${blocks.join("\n\n")}\n`;

  const names = [...defaults.keys()];
  const steps = names.filter((name) => /^space-\d+$/.test(name)).map((name) => JSON.stringify(name.slice("space-".length)));
  const ts = [
    `// ${HEADER}`,
    "",
    "/** Every design token, by CSS custom property name without the leading `--`. */",
    "export const TOKENS = [",
    ...names.map((name) => `  ${JSON.stringify(name)},`),
    "] as const;",
    "",
    "/** A design token name: `var(--${Token})` is its value. */",
    "export type Token = (typeof TOKENS)[number];",
    "",
    "/** A step of the 4 px spacing scale: `--space-${SpaceStep}`. */",
    `export type SpaceStep = ${steps.join(" | ")};`,
    "",
  ].join("\n");
  return { css, ts };
}

async function main(check: boolean): Promise<void> {
  const { css, ts } = await generate();
  const outputs: [string, string][] = [
    [CSS_OUT, css],
    [TS_OUT, ts],
  ];
  if (!check) {
    await Promise.all(outputs.map(([file, text]) => writeFile(`${ROOT}/${file}`, text)));
    return;
  }
  const stale: string[] = [];
  for (const [file, text] of outputs) {
    const current = await readFile(`${ROOT}/${file}`, "utf8").catch(() => undefined);
    if (current !== text) {
      stale.push(file);
    }
  }
  if (stale.length > 0) {
    console.error(`tokens: ${stale.join(" and ")} differ from tokens/*.json. Run \`bun run tokens\` and commit the result.`);
    process.exit(1);
  }
}

if (import.meta.main) {
  await main(process.argv.includes("--check"));
}
